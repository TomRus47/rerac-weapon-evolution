#!/usr/bin/env python3
"""Generate the developer INI reference from the public profile and launcher schema."""
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'launcher'))
import launcher_core as core
import schema

def cell(text):
    return str(text).replace('|','\\|').replace('\n',' ')

def field_type(section,key,value):
    if key in schema.COLORS:return 'RGB / default'
    if key in schema.BOOLEANS:return 'Boolean'
    if key=='level_up_sound':return 'help_notice / off'
    if key=='id':return 'Fixed game ID'
    low,high=core.numeric_range(section,key)
    kind='Integer' if key in schema.INTEGER else 'Number'
    if value.lower()=='default':kind+=' / default'
    return f'{kind}, {low:g}..{high:g}'

def explanation(section,key):
    return schema.help_text(section,key).split('\n',1)[1]

def generate():
    doc=core.profile_document((ROOT/'launcher/weapons.default.ini').read_bytes())
    lines=['# Configuration reference\n',
        'Generated by `python tools/mod/generate_config_reference.py` from '
        '`launcher/weapons.default.ini`, `launcher/schema.py` and the launcher validator. '
        'The default has '+str(len(doc.entries))+' entries.\n',
        'This reference describes public player fields and the launcher\'s accepted types/bounds. '
        'The Rust parser and consuming hook must also be maintained when adding a field; '
        'the runtime can impose additional context-specific limits. `default` is accepted only '
        'where implemented, such as colors and native-range sentinels. The internal real-HP session '
        'marker is intentionally absent from the public profile.\n',
        'Tick intervals use the 60 Hz simulation, not rendering FPS. Distances/multipliers retain '
        'the units and native fallback of their consuming weapon hook. HP/s applies to stream '
        'contact for Pyrocitor/Tesla and to the separate offensive aura for Taunter. XP thresholds '
        'are per transition. Inventory IDs are fixed; in-game names are localized by the game.\n',
        'See [Developer guide](DEVELOPER_GUIDE.md) for extension recipes and the damage/XP contracts.\n']
    for section in ['general','hud']:
        lines += [f'## [{section}]\n','| Key | Type / bounds | Default | Meaning |\n|---|---|---|---|\n']
        for key in doc.keys(section):
            value=doc.entries[section,key]
            lines.append('| `'+key+'` | '+cell(field_type(section,key,value))+' | `'+value+'` | '+cell(explanation(section,key))+' |\n')
    for name,(item,title) in schema.EDITOR_WEAPONS.items():
        section='weapon.'+name
        lines += [f'## {title} — ID {item}\n',f'INI prefix: `[{section}]`; grade sections: `[{section}.level1]` through `.level8`.\n',
                  '| Transition | Required XP |\n|---|---|\n']
        for i,key in enumerate(schema.XP,1):
            value='Gold purchase in NG+' if key=='xp_v5_to_v6' and name!='wrench' else doc.entries[section,key]
            lines.append(f'| V{i} → V{i+1} | {value} |\n')
        keys=list(dict.fromkeys(key for n in range(1,9) for key in doc.keys(section+f'.level{n}')))
        lines+=['\n| Grade field | V1 | V2 | V3 | V4 | V5 | V6 | V7 | V8 |\n|---|---|---|---|---|---|---|---|---|\n']
        for key in keys:
            values=[doc.entries.get((section+f'.level{n}',key),'—') for n in range(1,9)]
            lines.append('| `'+key+'` | '+' | '.join('`'+cell(v)+'`' for v in values)+' |\n')
        lines+=['\n| Grade field | Type / bounds | Meaning |\n|---|---|---|\n']
        for key in keys:
            actual=next(section+f'.level{n}' for n in range(1,9) if (section+f'.level{n}',key) in doc.entries)
            value=doc.entries[actual,key]
            lines.append('| `'+key+'` | '+cell(field_type(actual,key,value))+' | '+cell(explanation(actual,key))+' |\n')
        lines.append('\n')
    return '\n'.join(lines)

if __name__=='__main__':
    destination=ROOT/'docs/mod/CONFIG_REFERENCE.md'
    destination.write_text(generate(),encoding='utf-8')
    print(destination.relative_to(ROOT))
